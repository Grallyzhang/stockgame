// 生成 60 个交易日的 OHLCV（同 seed 结果一致，不存入存档）
export function buildMarket(seed) {
  const market = {};
  for (const co of COMPANIES) {
    const rng = mulberry32(seed ^ (co.id.length * 2654435761 + co.basePrice * 1000));
    const bars = [];
    for (let d = 1; d <= TOTAL_DAYS; d++) {
      const noise = (rng() * 2 - 1) * co.noise;
      const prev = d === 1 ? co.basePrice : bars[d - 2].close;
      let close = round2(anchor(co.id, d) * (1 + noise));
      let open = round2(prev * (1 + (rng() * 2 - 1) * 0.008));
      // 强制教学节点（在噪声之后覆盖，保证规则精确）：
      if (co.id === 'firefly' && d === 9) {               // 萤火涨停：精确 +10%（L6 教学日）
        close = round2(prev * 1.10);
        open = round2(prev * 1.04);
      }
      if (co.id === DIVIDEND.symbol && d === DIVIDEND.exDay) { // 松果除息：精确 −0.20（保证「总资产不变」恒等式）
        close = round2(prev - DIVIDEND.perShare);
        open = close;
      }
      let high = round2(Math.max(open, close) * (1 + rng() * 0.007));
      let low = round2(Math.min(open, close) * (1 - rng() * 0.007));
      if (co.id === 'firefly' && d === 9) { high = close; low = round2(Math.min(open, close) * (1 - rng() * 0.004)); }
      // 强制教学蜡烛覆写（K 线形态课，保证形态精确成立）
      const force = FORCE_CANDLES[co.id]?.[d];
      if (force) {
        const f = force(prev, bars);
        open = round2(f.open);
        close = round2(f.close);
        high = round2(f.high ?? Math.max(open, close) * 1.004);
        low = round2(f.low ?? Math.min(open, close) * 0.996);
      }
      const spike = EVENT_DAYS[co.id]?.includes(d) ? 2.8 : 1;
      const volume = Math.round(co.baseVol * (0.7 + rng() * 0.6) * spike);
      bars.push({ day: d, open, high, low, close, volume });
    }
    market[co.id] = bars;
  }
  return market;
}

